#!/usr/bin/env bash
set -euo pipefail

ROOT_DIR="$(cd "$(dirname "$0")/.." && pwd)"
JOLT_SRC="${JOLT_SRC:-$ROOT_DIR/JoltPhysics}"

if [[ ! -d "$JOLT_SRC/Build" ]]; then
	echo "JoltPhysics source not found at: $JOLT_SRC"
	echo "Set JOLT_SRC to the clone location."
	exit 1
fi

CONFIG="${1:-${CONFIGURATION:-Release}}"

BUILD_ROOT="${BUILD_ROOT:-$ROOT_DIR/build}"
OUTPUT_DIR="${OUTPUT_DIR:-$BUILD_ROOT/output}"
HEADERS_DIR="${HEADERS_DIR:-$BUILD_ROOT/headers}"

IOS_DEVICE_ARCHS="${IOS_DEVICE_ARCHS:-arm64}"
IOS_SIMULATOR_ARCHS="${IOS_SIMULATOR_ARCHS:-arm64;x86_64}"
IOS_DEPLOYMENT_TARGET="${IOS_DEPLOYMENT_TARGET:-}"

DOUBLE_PRECISION="${DOUBLE_PRECISION:-OFF}"
CROSS_PLATFORM_DETERMINISTIC="${CROSS_PLATFORM_DETERMINISTIC:-OFF}"
USE_ASSERTS="${USE_ASSERTS:-ON}"
DISABLE_CUSTOM_ALLOCATOR="${DISABLE_CUSTOM_ALLOCATOR:-OFF}"
ENABLE_OBJECT_STREAM="${ENABLE_OBJECT_STREAM:-ON}"
OBJECT_LAYER_BITS="${OBJECT_LAYER_BITS:-16}"
CPP_RTTI_ENABLED="${CPP_RTTI_ENABLED:-ON}"
DEBUG_RENDERER_IN_DEBUG_AND_RELEASE="${DEBUG_RENDERER_IN_DEBUG_AND_RELEASE:-ON}"
DEBUG_RENDERER_IN_DISTRIBUTION="${DEBUG_RENDERER_IN_DISTRIBUTION:-OFF}"
PROFILER_IN_DEBUG_AND_RELEASE="${PROFILER_IN_DEBUG_AND_RELEASE:-ON}"
PROFILER_IN_DISTRIBUTION="${PROFILER_IN_DISTRIBUTION:-OFF}"
JPH_USE_EXTERNAL_PROFILE="${JPH_USE_EXTERNAL_PROFILE:-OFF}"
INTERPROCEDURAL_OPTIMIZATION="${INTERPROCEDURAL_OPTIMIZATION:-OFF}"

for tool in cmake xcodebuild; do
	if ! command -v "$tool" >/dev/null 2>&1; then
		echo "Missing required tool: $tool"
		exit 1
	fi
done

COMMON_CMAKE_ARGS=(
	-DTARGET_UNIT_TESTS=OFF
	-DTARGET_HELLO_WORLD=OFF
	-DTARGET_PERFORMANCE_TEST=OFF
	-DTARGET_SAMPLES=OFF
	-DTARGET_VIEWER=OFF
	-DBUILD_SHARED_LIBS=OFF
	-DINTERPROCEDURAL_OPTIMIZATION=$INTERPROCEDURAL_OPTIMIZATION
	-DDOUBLE_PRECISION=$DOUBLE_PRECISION
	-DCROSS_PLATFORM_DETERMINISTIC=$CROSS_PLATFORM_DETERMINISTIC
	-DUSE_ASSERTS=$USE_ASSERTS
	-DDISABLE_CUSTOM_ALLOCATOR=$DISABLE_CUSTOM_ALLOCATOR
	-DENABLE_OBJECT_STREAM=$ENABLE_OBJECT_STREAM
	-DOBJECT_LAYER_BITS=$OBJECT_LAYER_BITS
	-DCPP_RTTI_ENABLED=$CPP_RTTI_ENABLED
	-DDEBUG_RENDERER_IN_DEBUG_AND_RELEASE=$DEBUG_RENDERER_IN_DEBUG_AND_RELEASE
	-DDEBUG_RENDERER_IN_DISTRIBUTION=$DEBUG_RENDERER_IN_DISTRIBUTION
	-DPROFILER_IN_DEBUG_AND_RELEASE=$PROFILER_IN_DEBUG_AND_RELEASE
	-DPROFILER_IN_DISTRIBUTION=$PROFILER_IN_DISTRIBUTION
	-DJPH_USE_EXTERNAL_PROFILE=$JPH_USE_EXTERNAL_PROFILE
	-DJPH_USE_DX12=OFF
	-DJPH_USE_VK=OFF
	-G Xcode
	-DCMAKE_SYSTEM_NAME=iOS
	-DCMAKE_XCODE_ATTRIBUTE_ONLY_ACTIVE_ARCH=NO
)

if [[ -n "${JPH_USE_MTL:-}" ]]; then
	COMMON_CMAKE_ARGS+=("-DJPH_USE_MTL=${JPH_USE_MTL}")
fi

if [[ -n "$IOS_DEPLOYMENT_TARGET" ]]; then
	COMMON_CMAKE_ARGS+=("-DCMAKE_OSX_DEPLOYMENT_TARGET=${IOS_DEPLOYMENT_TARGET}")
fi

DEVICE_BUILD_DIR="$BUILD_ROOT/iphoneos"
SIM_BUILD_DIR="$BUILD_ROOT/iphonesimulator"

cmake -S "$JOLT_SRC/Build" -B "$DEVICE_BUILD_DIR" \
	"${COMMON_CMAKE_ARGS[@]}" \
	-DCMAKE_OSX_SYSROOT=iphoneos \
	-DCMAKE_OSX_ARCHITECTURES="$IOS_DEVICE_ARCHS"

cmake --build "$DEVICE_BUILD_DIR" --config "$CONFIG" --target Jolt

cmake -S "$JOLT_SRC/Build" -B "$SIM_BUILD_DIR" \
	"${COMMON_CMAKE_ARGS[@]}" \
	-DCMAKE_OSX_SYSROOT=iphonesimulator \
	-DCMAKE_OSX_ARCHITECTURES="$IOS_SIMULATOR_ARCHS"

cmake --build "$SIM_BUILD_DIR" --config "$CONFIG" --target Jolt

DEVICE_LIB="$(find "$DEVICE_BUILD_DIR" -name "libJolt.a" -type f | head -n 1)"
SIM_LIB="$(find "$SIM_BUILD_DIR" -name "libJolt.a" -type f | head -n 1)"

if [[ -z "$DEVICE_LIB" || -z "$SIM_LIB" ]]; then
	echo "libJolt.a not found. Device: '$DEVICE_LIB' Simulator: '$SIM_LIB'"
	exit 1
fi

rm -rf "$HEADERS_DIR"
mkdir -p "$HEADERS_DIR"
/usr/bin/rsync -a \
	--include='*/' \
	--include='*.h' \
	--include='*.hpp' \
	--include='*.inl' \
	--include='*.inc' \
	--exclude='*' \
	"$JOLT_SRC/Jolt/" "$HEADERS_DIR/Jolt/"

is_on() {
	local val
	val="$(printf '%s' "$1" | tr '[:lower:]' '[:upper:]')"
	case "$val" in
		ON|1|YES|TRUE) return 0 ;;
		*) return 1 ;;
	esac
}

config_in() {
	local cfg="$1"
	shift
	for item in "$@"; do
		if [[ "$cfg" == "$item" ]]; then
			return 0
		fi
	done
	return 1
}

DEBUG_RENDERER_ACTIVE=0
if is_on "$DEBUG_RENDERER_IN_DISTRIBUTION"; then
	DEBUG_RENDERER_ACTIVE=1
elif is_on "$DEBUG_RENDERER_IN_DEBUG_AND_RELEASE" && config_in "$CONFIG" Debug Release ReleaseASAN ReleaseUBSAN ReleaseTSAN; then
	DEBUG_RENDERER_ACTIVE=1
fi

PROFILER_ACTIVE=0
if is_on "$PROFILER_IN_DISTRIBUTION"; then
	PROFILER_ACTIVE=1
elif is_on "$PROFILER_IN_DEBUG_AND_RELEASE" && config_in "$CONFIG" Debug Release ReleaseASAN ReleaseUBSAN ReleaseTSAN; then
	PROFILER_ACTIVE=1
fi

DISABLE_TEMP_ALLOCATOR_ACTIVE=0
if config_in "$CONFIG" ReleaseASAN ReleaseTSAN; then
	DISABLE_TEMP_ALLOCATOR_ACTIVE=1
	DISABLE_CUSTOM_ALLOCATOR=ON
fi

CONFIG_HEADER_PATH="$HEADERS_DIR/Jolt/JoltBuildSettings.h"
cat > "$CONFIG_HEADER_PATH" <<JPH_EOF
// Generated by scripts/build_jolt_xcframework.sh. Include this before any Jolt headers.
#pragma once

#define JPH_OBJECT_LAYER_BITS ${OBJECT_LAYER_BITS}
JPH_EOF

if is_on "$DOUBLE_PRECISION"; then
	echo "#define JPH_DOUBLE_PRECISION" >> "$CONFIG_HEADER_PATH"
fi
if is_on "$CROSS_PLATFORM_DETERMINISTIC"; then
	echo "#define JPH_CROSS_PLATFORM_DETERMINISTIC" >> "$CONFIG_HEADER_PATH"
fi
if is_on "$USE_ASSERTS"; then
	echo "#define JPH_ENABLE_ASSERTS" >> "$CONFIG_HEADER_PATH"
fi
if is_on "$ENABLE_OBJECT_STREAM"; then
	echo "#define JPH_OBJECT_STREAM" >> "$CONFIG_HEADER_PATH"
fi
if is_on "$DISABLE_CUSTOM_ALLOCATOR"; then
	echo "#define JPH_DISABLE_CUSTOM_ALLOCATOR" >> "$CONFIG_HEADER_PATH"
fi
if [[ "$DISABLE_TEMP_ALLOCATOR_ACTIVE" == "1" ]]; then
	echo "#define JPH_DISABLE_TEMP_ALLOCATOR" >> "$CONFIG_HEADER_PATH"
fi
if [[ "$DEBUG_RENDERER_ACTIVE" == "1" ]]; then
	echo "#define JPH_DEBUG_RENDERER" >> "$CONFIG_HEADER_PATH"
fi
if [[ "$PROFILER_ACTIVE" == "1" ]]; then
	if is_on "$JPH_USE_EXTERNAL_PROFILE"; then
		echo "#define JPH_EXTERNAL_PROFILE" >> "$CONFIG_HEADER_PATH"
	else
		echo "#define JPH_PROFILE_ENABLED" >> "$CONFIG_HEADER_PATH"
	fi
fi

mkdir -p "$OUTPUT_DIR"
OUTPUT_XCFRAMEWORK="$OUTPUT_DIR/JoltPhysics.xcframework"
rm -rf "$OUTPUT_XCFRAMEWORK"

xcodebuild -create-xcframework \
	-library "$DEVICE_LIB" -headers "$HEADERS_DIR" \
	-library "$SIM_LIB" -headers "$HEADERS_DIR" \
	-output "$OUTPUT_XCFRAMEWORK"

ZIP_PATH="${OUTPUT_XCFRAMEWORK}.zip"
rm -f "$ZIP_PATH"
/usr/bin/ditto -c -k --sequesterRsrc --keepParent "$OUTPUT_XCFRAMEWORK" "$ZIP_PATH"

if [[ -n "${GITHUB_OUTPUT:-}" ]]; then
	echo "xcframework_path=$OUTPUT_XCFRAMEWORK" >> "$GITHUB_OUTPUT"
	echo "zip_path=$ZIP_PATH" >> "$GITHUB_OUTPUT"
fi

echo "Created: $OUTPUT_XCFRAMEWORK"
echo "Zipped:  $ZIP_PATH"
